/**
 * loadTarget.js -- the single point at which a test suite is bound to a
 * pipeline stage.
 *
 * Every suite entry under tests/entries/ reaches the code under test
 * through here, so one environment variable re-points the ENTIRE benchmark:
 *
 *   TARGET_DIR=dataset/00_raw                       npx jest   # ground truth
 *   TARGET_DIR=dataset/01_obfuscated/level_3        npx jest   # obfuscator sanity
 *   TARGET_DIR=dataset/02_deobfuscated/gpt5_cot     npx jest   # a run under test
 *
 * The suites themselves are byte-identical copies of the upstream maintainers'
 * tests (tests/upstream/, hashes in tests/SOURCES.json). They never
 * mention a path -- the stubs generated by tests/runner/build.js redirect their
 * `require('../')` here. That is what keeps the oracle independent of us.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const TARGET_DIR = process.env.TARGET_DIR || 'dataset/00_raw';

function targetPath(id) {
  return path.resolve(ROOT, TARGET_DIR, `${id}.js`);
}

/**
 * Evaluate a corpus file, fresh, inside Jest's module registry.
 *
 * `jest.isolateModules` rather than `delete require.cache[...]`: Jest's
 * require.cache is a shim over its own registry, so the usual cache-busting
 * dance silently does nothing there. Suites that undo a global mutation by
 * reloading the module -- slugify's extend() tests -- would then run their
 * post-reset assertion against polluted state and fail for a harness reason.
 *
 * It must stay inside Jest's registry (rather than compiling the file with
 * Node's own Module) so the corpus and the suite share one set of intrinsics;
 * a cross-realm Array makes deepStrictEqual fail on identical data. Babel still
 * never sees the file -- dataset/ is excluded in transformIgnorePatterns.
 */
function loadFresh(abs) {
  let mod;
  if (typeof jest !== 'undefined' && typeof jest.isolateModules === 'function') {
    jest.isolateModules(() => { mod = require(abs); });
  } else {
    delete require.cache[require.resolve(abs)];
    mod = require(abs);
  }
  return mod;
}

/**
 * Load one corpus file. Throws with the stage name in the message so a missing
 * or unparseable deobfuscation output is never mistaken for a semantic failure.
 */
function loadTarget(id, opts = {}) {
  const abs = targetPath(id);
  if (!fs.existsSync(abs)) {
    throw new Error(`[harness] ${id}.js not found in TARGET_DIR=${TARGET_DIR} (looked at ${abs})`);
  }
  let mod;
  try {
    mod = loadFresh(abs);
  } catch (err) {
    throw new Error(`[harness] ${id}.js failed to load from ${TARGET_DIR}: ${err.message}`);
  }
  // Some entry modules are bundler output whose real export sits on `.default`.
  // Opt in per suite rather than globally -- a target that legitimately exports
  // an object with a `default` key must not be silently unwrapped.
  if (opts.unwrapDefault && mod && mod.default !== undefined) return mod.default;
  return mod;
}

loadTarget.targetPath = targetPath;
loadTarget.TARGET_DIR = TARGET_DIR;

module.exports = loadTarget;
