/**
 * build.js -- materialise the harness described by suites.js.
 *
 * Writes, for every suite:
 *   tests/upstream/<id>/<stub>          re-export of the TARGET_DIR corpus file
 *   tests/entries/generated/<id>.test.js  Jest entry that runs the vendored files
 *
 * Both are generated and carry a banner saying so; nothing here touches a
 * vendored file. Re-run after editing suites.js:  node tests/runner/build.js
 */
const fs = require('fs');
const path = require('path');

const SUITES = require('./suites');
const ROOT = path.resolve(__dirname, '../..');
const UPSTREAM = path.join(ROOT, 'tests/upstream');
const GENERATED = path.join(ROOT, 'tests/entries/generated');
const prov = Object.fromEntries(
  JSON.parse(fs.readFileSync(path.join(ROOT, 'tests/SOURCES.json'), 'utf8')).map((r) => [r.id, r])
);

const HANDWRITTEN = path.join(ROOT, 'tests/entries/handwritten');

// tests/entries/generated/ holds only generated files, so it is rebuilt from empty --
// that way a suite removed from suites.js cannot leave a stale entry behind.
// Hand-written entries live in tests/entries/handwritten/ and are never touched here.
fs.rmSync(GENERATED, { recursive: true, force: true });
fs.mkdirSync(GENERATED, { recursive: true });

let stubCount = 0;
let entryCount = 0;

for (const [id, spec] of Object.entries(SUITES)) {
  // --- stubs ---------------------------------------------------------------
  for (const entry of spec.stubs) {
    // A stub is normally a plain re-export. Some packages publish a SECOND
    // entry point that is a thin wrapper over the first -- rfdc/default.js is
    // literally `module.exports = require('./index.js')()` -- and its suite
    // requires both. Such a stub declares `{ path, expr, note }` so the wrapper
    // is reproduced rather than aliased to the factory itself.
    const stub = typeof entry === 'string' ? entry : entry.path;
    const dest = path.join(UPSTREAM, id, stub);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    const up = path.relative(path.dirname(dest), path.join(ROOT, 'tests/runner/load-target')).split(path.sep).join('/');
    const req = `require('${up.startsWith('.') ? up : './' + up}')('${id}')`;
    const body = typeof entry === 'string' ? req : entry.expr.replace('$TARGET', req);
    fs.writeFileSync(dest, [
      '// GENERATED by tests/runner/build.js -- not upstream code, do not edit.',
      `// Stands in for the package root that ${prov[id].npm_package}'s own tests require,`,
      '// so those tests load the corpus file for the current TARGET_DIR instead.',
      ...(typeof entry === 'string' ? [] : [`// ${entry.note}`]),
      `module.exports = ${body};`,
      '',
    ].join('\n'));
    stubCount += 1;
  }

  // --- Jest entry ----------------------------------------------------------
  if (spec.custom) continue;
  const p = prov[id];
  const skips = (spec.skipTests || []).length
    ? [
        '// Declared in tests/runner/suites.js with a reason; reported as skipped,',
        '// never silently dropped. See docs/TESTS.md.',
        `global.__SKIP_TESTS__ = ${JSON.stringify(spec.skipTests.map((s) => s.name))};`,
        '',
      ].join('\n')
    : '';
  let requires = spec.entries.map((e) => `require('../../upstream/${id}/${e}');`).join('\n');
  if (spec.resetArgv) {
    requires = [
      '// This suite inspects process.argv; under Jest that argv is Jest\'s, not',
      '// its own. Blanked for the load so upstream takes its default path.',
      'const __argv = process.argv;',
      'process.argv = [__argv[0], __argv[1]];',
      'try {',
      requires.split('\n').map((l) => `  ${l}`).join('\n'),
      '} finally {',
      '  process.argv = __argv;',
      '}',
    ].join('\n');
  }
  requires = skips + requires;
  fs.writeFileSync(path.join(GENERATED, `${id}.test.js`), [
    '/**',
    ` * ${id} -- official upstream suite of ${p.npm_package}@${p.npm_version}.`,
    ' *',
    ` * Vendored byte-identical from ${p.origin}`,
    ` * at ${p.test_source === 'npm' ? `tarball sha1 ${p.pin}` : `commit ${p.pin}`}.`,
    ' * Digests: tests/SOURCES.json. Binding: tests/runner/suites.js.',
    ' * GENERATED by tests/runner/build.js -- do not edit.',
    ' */',
    requires,
    '',
  ].join('\n'));
  entryCount += spec.entries.length;
}

// A suite marked custom contributes nothing above; if its hand-written entry is
// missing, the corpus file would silently go unscored.
const missingCustom = Object.entries(SUITES)
  .filter(([, spec]) => spec.custom)
  .map(([id]) => id)
  .filter((id) => !fs.existsSync(path.join(HANDWRITTEN, `${id}.test.js`)));

console.log(`[build] ${stubCount} stubs, ${entryCount} vendored entry files across ${Object.keys(SUITES).length} suites`);
console.log(`[build] ${Object.values(SUITES).filter((s) => s.custom).length - missingCustom.length} hand-written entries present in tests/entries/handwritten/`);
if (missingCustom.length) {
  for (const id of missingCustom) console.error(`[build] MISSING hand-written entry: tests/entries/handwritten/${id}.test.js`);
  process.exit(1);
}
